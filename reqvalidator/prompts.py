SYSTEM = """Ты — старший системный аналитик и ревьюер требований в банке. Ты применяешь ISO/IEC/IEEE 29148:2018 \
(п. 5.2.5 — свойства требования, п. 5.2.6 — свойства набора) и IEEE Std 830-1998 (п. 4.3). \
Ты делаешь СТАТИЧЕСКОЕ РЕВЬЮ текста требований до разработки: ищешь дефекты формулировок, а не тестируешь программу.

Жёсткие правила:
1. Опирайся только на текст документа. Ничего не выдумывай: ни фактов, ни цитат, ни номеров строк. Если сомневаешься — не заявляй.
2. Каждое замечание обязано содержать ДОСЛОВНУЮ цитату из документа — копия символ в символ, без пересказа, без правок \
и без markdown-разметки (**, `, |), длиной до 250 символов, целиком из одного места текста.
3. Если дефект — ОТСУТСТВИЕ чего-то (нет порога, нет обработки ошибки, нет приёмки), цитируй то место, где это должно было быть описано, \
и в проблеме прямо назови, чего именно нет.
4. Одна проблема — одно замечание. Не дублируй, не раздувай список мелочами. Хорошее требование — это пустой список замечаний.
5. Формулируй конкретно: что именно не так → чем это мешает разработке или тестированию (какие две трактовки возможны, какой тест нельзя написать) \
→ что исправить. Запрещены общие фразы вроде «требование нечёткое» без указания, что именно нечётко.
6. Не предлагай собственных бизнес-решений как факт; в предлагаемых формулировках неизвестное помечай как «[уточнить: …]».
7. Пиши на русском языке. Отвечай ТОЛЬКО JSON по заданной схеме, без markdown и пояснений вне JSON.

Серьёзность:
- critical: """ + SEVERITY_DEF["critical"] + """
- major: """ + SEVERITY_DEF["major"] + """
- minor: """ + SEVERITY_DEF["minor"]


def extract_prompt(doc_name: str, numbered_text: str, line_range: tuple[int, int], total_lines: int) -> str:
    return f"""Задача: выделить из документа «{doc_name}» ВСЕ отдельные требования. Проверять их пока не нужно.
Ниже строки {line_range[0]}–{line_range[1]} из {total_lines}; каждая строка начинается с метки [L<номер>] — метку в цитату НЕ включай.

ЧТО СЧИТАТЬ ТРЕБОВАНИЕМ (по одному элементу на каждое):
- функциональные требования (пункты Ф-1, Ф-2 …); нефункциональные; требования к данным, интеграции, тестированию;
- цели и бизнес-правила, из которых выводятся требования (kind = business_rule);
- требования к UI/UX и описания процесса, если они что-то предписывают (kind = interface / other);
- каждый критерий приёмки — одна строка таблицы = один элемент (kind = acceptance);
- для API/интерфейсных спецификаций: каждое правило логики, каждое «особое правило», каждый параметр запроса и ответа, \
каждый статус/код ответа, а также предписания по методу/URL/авторизации (kind = integration);
- предложения вида «должен / должна / должно / должны», «система …», «клиент получает …» вне таблиц-шаблонов.
НЕ СЧИТАТЬ ТРЕБОВАНИЕМ: заголовки, служебные поля шаблона (название, продукт, роли, ссылка на Jira), чек-лист «Ревью требований», \
блок согласующих, пустые заглушки, примеры curl/JSON сами по себе (но их содержание можно использовать как контекст).

ГРАНУЛЯРНОСТЬ: если в документе есть своя нумерация (Ф-1, НФТ-2 …), один пронумерованный пункт = один элемент, даже если внутри несколько правил \
(склейку правил оценит проверка). Если нумерации нет — одно предложение/одна строка таблицы с предписанием = один элемент. \
Заглушки вроде «заполняются тестировщиками» в разделе, где должны быть требования, тоже включи (kind = other): это дефект, который надо показать.

ПОЛЯ: doc_id — идентификатор из документа как написан («Ф-1») или null; section — ближайший раздел; kind; \
quote — ДОСЛОВНАЯ цитата всего требования (до 400 символов, без разметки **, |, `); summary — краткая формулировка до 15 слов своими словами.
Элементы верни в порядке следования в документе.

ДОКУМЕНТ:
{numbered_text}"""


def extract_missing_prompt(numbered_text: str, missing_ids: list[str]) -> str:
    ids = ", ".join(missing_ids)
    return f"""В документе есть пронумерованные пункты, которые не попали в список требований: {ids}.
Верни ТОЛЬКО эти пункты в том же формате (doc_id, section, kind, quote, summary). Цитата — дословно, без разметки.

ДОКУМЕНТ:
{numbered_text}"""


def check_prompt(doc_name: str, numbered_doc: str, batch: list[dict]) -> str:
    return f"""Проверь отдельные требования документа «{doc_name}» по критериям качества требования.

КРИТЕРИИ (код — название: суть):
{criteria_for_prompt(REQ_CRITERIA)}

Как работать:
- Для каждого требования из списка проверь ВСЕ критерии. Нарушенный критерий = замечание в findings (код критерия, серьёзность, цитата, проблема, исправление).
- not_applicable — коды критериев, которые к ЭТОМУ виду требования не применимы по смыслу (например IMPL для критерия приёмки, FEAS для чисто описательной цели). \
Не злоупотребляй: если критерий применим, но выполнен — просто не создавай замечание.
- Противоречия МЕЖДУ разными требованиями здесь не разбирай (их ищет проверка набора). В CONS фиксируй только противоречия внутри самой формулировки \
или её несовпадение с явными числами/примерами/таблицами, прямо приведёнными в этом же требовании.
- Используй весь документ как контекст: определения, таблицы, диаграммы, смежные разделы. Если термин определён в другом месте документа — это не дефект.
- «Подсказки линтера» — это лишь список слов-кандидатов; решай сам, дефект ли это в данном контексте.
- До 6 замечаний на требование, самые важные первыми.
- rewrite — улучшенная формулировка этого требования, если есть замечания (неизвестное помечай «[уточнить: …]»), иначе null.
- В ответе по каждому требованию верни тот же rid, что и во входном списке; не пропускай требования.

ТРЕБОВАНИЯ ДЛЯ ПРОВЕРКИ (JSON):
{json.dumps(batch, ensure_ascii=False, indent=1)}

ПОЛНЫЙ ДОКУМЕНТ (контекст):
{numbered_doc}"""


def set_prompt(doc_name: str, numbered_doc: str, table: list[dict], req_findings: list[dict], doc_hints: list[str]) -> str:
    return f"""Проверь НАБОР требований документа «{doc_name}» как целое.

КРИТЕРИИ НАБОРА (код — название: суть):
{criteria_for_prompt(SET_CRITERIA)}

Что искать (каждая находка — отдельное замечание с дословными цитатами):
1. Противоречия между требованиями, между требованиями и критериями приёмки/примерами, между частями документа (S_CONS): процитируй ОБА места, \
в involved укажи rid обоих требований. Сверяй числа, даты, условия, ограничения («максимум один» vs «каждый раз»), коды ответов, типы данных.
2. Пропуски (S_COMPL): какие аспекты, нужные для разработки и тестирования, не описаны вовсе (ошибочные и пограничные сценарии, нефункциональные \
аспекты — безопасность, производительность, надёжность, аудит/логирование, откат, поведение при недоступности смежных систем, данные и их хранение, \
права и сущности вроде валют/статусов/устройств). Цитируй место, где пробел проявляется. Называй конкретные недостающие вещи, а не «мало деталей».
3. Расхождения терминов, данных, интерфейсов (S_TERMS): одно и то же названо/описано по-разному в разных разделах/частях; части документа, ссылающиеся друг на друга.
4. Покрытие (S_COVER, S_VERIF): какие требования не покрыты критериями приёмки, каких проверок не хватает (границы, негативные кейсы, нефункциональные), \
есть ли связь цель → требования → приёмка. Перечисли rid непокрытых требований в involved.
5. Структура и процесс (S_STRUCT, S_PRIO): версионность, согласующие, заполненность чек-листов и разделов шаблона (сверь заявленное в чек-листе \
с тем, что реально есть в документе), приоритеты, идентификаторы у всех групп требований.
6. Риски и реализуемость (S_FEAS): безопасность, персональные данные, влияние на смежные системы, откат, операционные риски.

Правила:
- Не повторяй замечания, которые относятся только к одному требованию и уже перечислены ниже в «Замечаниях к отдельным требованиям». \
Сюда — только то, что видно лишь на уровне набора или связывает несколько мест.
- Объединяй однотипные мелкие находки в одно замечание. Всего не более 25 замечаний, самые важные первыми.
- involved — rid из таблицы требований (R-001 …); если замечание о документе в целом, оставь пустой список.
- quotes — 1–3 дословные цитаты (до 250 символов каждая).

ТАБЛИЦА ТРЕБОВАНИЙ (JSON):
{json.dumps(table, ensure_ascii=False, indent=1)}

ЗАМЕЧАНИЯ К ОТДЕЛЬНЫМ ТРЕБОВАНИЯМ (уже найдены, кратко):
{json.dumps(req_findings, ensure_ascii=False, indent=1)}

ПОДСКАЗКИ ЛИНТЕРА ПО ДОКУМЕНТУ:
{json.dumps(doc_hints, ensure_ascii=False)}

ПОЛНЫЙ ДОКУМЕНТ:
{numbered_doc}"""


def finalize_prompt(doc_name: str, counts: dict, findings: list[dict]) -> str:
    return f"""Ты закончил ревью документа «{doc_name}». Сформулируй итог для автора и заказчика.

Статистика: {json.dumps(counts, ensure_ascii=False)}

Все замечания (id, серьёзность, критерий, к чему относится, суть):
{json.dumps(findings, ensure_ascii=False, indent=1)}

Верни:
- rationale: 2–5 предложений — можно ли по этому документу начинать разработку и тестирование и почему (опирайся на критичные замечания, называй их id);
- priorities: от 3 до 8 пунктов «что исправить в первую очередь», по убыванию важности. Сначала то, что блокирует разработку и тестирование \
(противоречия, непроверяемое, неполное), затем остальное. Группируй связанные замечания в один пункт; в refs перечисли id замечаний из списка выше (только существующие id). \
title — императивом и конкретно («Устранить противоречие между Ф-3 и Ф-4: …»), why — одно предложение."""
